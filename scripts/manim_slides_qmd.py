#!/usr/bin/env python3
"""Lay out a manim-slides render as Quarto revealjs slides.

manim-slides splits a scene into segments at each `self.next_slide()`. This
copies the segments into the deck's videos/<name>/ and writes _<name>.qmd: one
headless slide per segment, the segment as its background video. Pull it into
index.qmd with `{{< include _<name>.qmd >}}` (the underscore keeps Quarto from
rendering it as a page).

Clicker semantics match `manim-slides present`:
  - a segment plays once and holds on its last frame until the click
  - a loop segment repeats until the click
  - a segment followed by a loop runs straight into it (data-autoslide)

Segments cut between slides with no transition, so the clip reads as one video.

Run from the deck directory, after `manim-slides render`:
    python3 ../../scripts/manim_slides_qmd.py <SceneName> <name> [--slides slides]

Stdlib only; needs ffprobe on the PATH for the autoslide durations.
"""

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

BG = "#0d1117"


def duration_ms(path):
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "csv=p=0", str(path)],
        check=True, capture_output=True, text=True,
    ).stdout
    return int(float(out) * 1000)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("scene", help="Slide class name, e.g. TwoElementInterferometerSlides")
    ap.add_argument("name", help="Output name: videos/<name>/ and _<name>.qmd")
    ap.add_argument("--slides", default="slides", type=Path,
                    help="manim-slides output folder (default: slides)")
    args = ap.parse_args()

    cfg_path = args.slides / f"{args.scene}.json"
    if not cfg_path.exists():
        sys.exit(f"{cfg_path} not found: run `manim-slides render` first")
    segments = json.loads(cfg_path.read_text())["slides"]

    if not Path("videos").is_symlink():
        print("warning: videos/ is not a symlink into /data/talks/ "
              "(see _wiki/infrastructure/large-data.md)", file=sys.stderr)
    out_dir = Path("videos") / args.name
    if out_dir.exists():
        shutil.rmtree(out_dir)   # a re-render can produce fewer segments
    out_dir.mkdir(parents=True)

    blocks = []
    for i, seg in enumerate(segments):
        src = Path(seg["file"])
        if not src.is_absolute():   # relative to where `render` ran
            src = args.slides.parent / src
        dst = out_dir / f"{i + 1:02d}{src.suffix}"
        shutil.copyfile(src, dst)

        attrs = [
            f'background-video="{dst.as_posix()}"',
            'background-video-muted="true"',
            'background-size="contain"',
            f'background-color="{BG}"',
        ]
        if seg.get("loop"):
            attrs.append('background-video-loop="true"')
        nxt = segments[i + 1] if i + 1 < len(segments) else None
        if nxt is not None and (nxt.get("loop") or seg.get("auto_next")):
            attrs.append(f'data-autoslide="{duration_ms(dst)}"')
        if i > 0:
            attrs += ['transition="none"', 'background-transition="none"']
        # .plain-figure hides the empty heading (and the theme's rule under it)
        blocks.append("## {.plain-figure " + " ".join(attrs) + "}\n")

    header = (f"<!-- Generated by scripts/manim_slides_qmd.py from "
              f"{args.scene}; do not edit, re-run it. -->\n\n")
    Path(f"_{args.name}.qmd").write_text(header + "\n".join(blocks))
    loops = sum(bool(s.get("loop")) for s in segments)
    print(f"{len(segments)} segments ({loops} loops) -> {out_dir}/, _{args.name}.qmd")


if __name__ == "__main__":
    main()
